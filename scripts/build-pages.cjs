// Generate the static entry points served by GitHub Pages.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const check = process.argv.includes("--check");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const context = vm.createContext({ module: { exports: {} } });
for (const file of ["config.js", "script.js"]) {
  vm.runInContext(read(file), context, { filename: file });
}
const pages = context.module.exports;
const shell = read("index.html").replace(/\r\n/g, "\n");

function escape(value) {
  return value.replace(/[&<>"']/g, character => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  })[character]);
}

function render(page) {
  const title = escape(page.title);
  const description = escape(page.description);
  const url = escape(page.url);
  return shell
    .replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by scripts/build-pages.cjs -->")
    .replace(/<title>[^<]*<\/title>/, () => "<title>" + title + "</title>")
    .replace(/(<meta (?:name|property)="(?:description|og:description|twitter:description)" content=")[^"]*/g, (_, start) => start + description)
    .replace(/(<meta (?:property="og:title"|name="twitter:title") content=")[^"]*/g, (_, start) => start + title)
    .replace(/(<link rel="canonical" href="|<meta property="og:url" content=")[^"]*/g, (_, start) => start + url)
    .replace(/(<meta name="robots" content=")[^"]*/, (_, start) => start + (page.noindex ? "noindex, follow" : "index, follow, max-image-preview:large"))
    .replace(/<noscript>[\s\S]*?<\/noscript>/, () =>
      '<noscript><main class="wrap">\n  <h1>' + title + '</h1>\n  <p>' + description +
      '</p>\n  <p>Enable JavaScript to use the site, or email <a href="mailto:info@robatfit.com">info@robatfit.com</a>.</p>\n' +
      '  <p><a href="/">Back to ROBAT</a></p>\n</main></noscript>');
}

function output(file, contents) {
  const target = path.join(root, file);
  if (check) {
    if (!fs.existsSync(target) || read(file).replace(/\r\n/g, "\n") !== contents) {
      throw new Error(file + " is out of date. Run node scripts/build-pages.cjs");
    }
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, contents);
}

for (const page of pages) {
  if (page.path === "/") continue;
  output(page.path.slice(1) + "index.html", render(page));
}

const sitemap = pages.filter(page => !page.noindex)
  .map(page => "  <url><loc>" + escape(page.url) + "</loc></url>")
  .join("\n");
output("sitemap.xml", '<?xml version="1.0" encoding="UTF-8"?>\n' +
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + sitemap + "\n</urlset>\n");
console.log((check ? "Verified " : "Generated ") + (pages.length - 1) + " path entry points and the sitemap.");
